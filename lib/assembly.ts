import type { CircuitJson } from "circuit-json"
import { jscadToStep } from "jscad-to-step"
import {
  ApplicationContext,
  ApplicationProtocolDefinition,
  Axis2Placement3D,
  CartesianPoint,
  ContextDependentShapeRepresentation,
  Direction,
  ItemDefinedTransformation,
  NextAssemblyUsageOccurrence,
  Product,
  ProductContext,
  ProductDefinition,
  ProductDefinitionContext,
  ProductDefinitionFormation,
  ProductDefinitionShape,
  Repository,
  ShapeDefinitionRepresentation,
  ShapeRepresentation,
  Unknown,
} from "stepts"
import { importStepModelGeometry } from "./step-model-merger"
import {
  asVector3,
  toRadians,
  transformDirection,
} from "./step-model-merger/vector-utils"
import { normalizeStepNumericExponents } from "./step-text-utils"
import { VERSION } from "./version"

/** Export JSCAD printed parts as distinct named children of a STEP assembly. */
export function circuitJsonToAssemblyStep(
  circuitJson: CircuitJson,
  {
    productName = "Combined Assembly",
    sourceComponentId,
  }: { productName?: string; sourceComponentId?: string } = {},
): string {
  const parts = circuitJson
    .filter((item) => item.type === "source_component")
    .filter((item) => item.ftype === "printedpart")
    .filter(
      (item) =>
        sourceComponentId === undefined ||
        item.source_component_id === sourceComponentId,
    )
  if (parts.length === 0) {
    throw new Error("No assembly.printedpart elements found to export")
  }

  const repo = new Repository()
  const appContext = repo.add(new ApplicationContext("automotive design"))
  repo.add(
    new ApplicationProtocolDefinition(
      "international standard",
      "automotive_design",
      2010,
      appContext,
    ),
  )
  const productContext = repo.add(
    new ProductContext("", appContext, "mechanical"),
  )
  const definitionContext = repo.add(
    new ProductDefinitionContext("part definition", appContext, "design"),
  )
  const createProduct = (id: string, name: string) => {
    const product = repo.add(
      new Product(id, name, `Generated by circuit-json-to-step v${VERSION}`, [
        productContext,
      ]),
    )
    const formation = repo.add(new ProductDefinitionFormation("", "", product))
    const definition = repo.add(
      new ProductDefinition("design", "", formation, definitionContext),
    )
    const shape = repo.add(new ProductDefinitionShape("", "", definition))
    return { definition, shape }
  }

  const lengthUnit = repo.add(
    new Unknown("", [
      "( LENGTH_UNIT() NAMED_UNIT(*) SI_UNIT(.MILLI.,.METRE.) )",
    ]),
  )
  const angleUnit = repo.add(
    new Unknown("", [
      "( NAMED_UNIT(*) PLANE_ANGLE_UNIT() SI_UNIT($,.RADIAN.) )",
    ]),
  )
  const solidAngleUnit = repo.add(
    new Unknown("", [
      "( NAMED_UNIT(*) SI_UNIT($,.STERADIAN.) SOLID_ANGLE_UNIT() )",
    ]),
  )
  const uncertainty = repo.add(
    new Unknown("UNCERTAINTY_MEASURE_WITH_UNIT", [
      "LENGTH_MEASURE(1.E-07)",
      `${lengthUnit}`,
      "'distance_accuracy_value'",
      "'Maximum Tolerance'",
    ]),
  )
  const context = repo.add(
    new Unknown("", [
      `( GEOMETRIC_REPRESENTATION_CONTEXT(3) GLOBAL_UNCERTAINTY_ASSIGNED_CONTEXT((${uncertainty})) GLOBAL_UNIT_ASSIGNED_CONTEXT((${lengthUnit},${angleUnit},${solidAngleUnit})) REPRESENTATION_CONTEXT('','3D') )`,
    ]),
  )
  const createPlacement = (
    position = { x: 0, y: 0, z: 0 },
    rotation = { x: 0, y: 0, z: 0 },
  ) => {
    const radians = toRadians(rotation)
    const axis = repo.add(
      new Direction("", ...transformDirection([0, 0, 1], radians)),
    )
    const referenceDirection = repo.add(
      new Direction("", ...transformDirection([1, 0, 0], radians)),
    )
    const point = repo.add(
      new CartesianPoint("", position.x, position.y, position.z),
    )
    return repo.add(new Axis2Placement3D("", point, axis, referenceDirection))
  }

  const assembly = createProduct(productName, productName)
  const origin = createPlacement()
  const representation = repo.add(
    new ShapeRepresentation(productName, [origin], context),
  )
  repo.add(new ShapeDefinitionRepresentation(assembly.shape, representation))

  for (const part of parts) {
    const models = circuitJson
      .filter((item) => item.type === "cad_component")
      .filter((item) => item.source_component_id === part.source_component_id)
    if (models.length === 0 || models.some((model) => !model.model_jscad)) {
      throw new Error(
        `Printed part "${part.name}" needs JSCAD geometry for STEP export`,
      )
    }

    for (const model of models) {
      const modelOrigin = asVector3(model.model_origin_position)
      const scale = model.model_unit_to_mm_scale_factor ?? 1
      // Keep geometry local; rigid placement belongs to the assembly occurrence.
      const geometry = jscadToStep({
        type: "scale",
        factors: [scale, scale, scale],
        shape: {
          type: "translate",
          vector: [-modelOrigin.x, -modelOrigin.y, -modelOrigin.z],
          shape: model.model_jscad!,
        },
      })
      const imported = importStepModelGeometry(repo, geometry, part.name)
      if (imported.solids.length === 0) {
        throw new Error(
          `Printed part "${part.name}" has no solid geometry to export`,
        )
      }
      imported.representation.resolve(repo).items.unshift(imported.origin)
      const child = createProduct(model.cad_component_id, part.name)
      repo.add(
        new ShapeDefinitionRepresentation(child.shape, imported.representation),
      )

      const placement = createPlacement(
        asVector3(model.position),
        asVector3(model.rotation),
      )
      representation.resolve(repo).items.push(placement)
      const usage = repo.add(
        new NextAssemblyUsageOccurrence(
          model.cad_component_id,
          part.name,
          "",
          assembly.definition,
          child.definition,
          part.name,
        ),
      )
      const transformation = repo.add(
        new ItemDefinedTransformation("", "", imported.origin, placement),
      )
      const relationship = repo.add(
        new Unknown("", [
          `( REPRESENTATION_RELATIONSHIP('','',${imported.representation},${representation}) REPRESENTATION_RELATIONSHIP_WITH_TRANSFORMATION(${transformation}) SHAPE_REPRESENTATION_RELATIONSHIP() )`,
        ]),
      )
      // stepts' ProductDefinitionShape type currently excludes product relationships.
      const usageShape = repo.add(
        new Unknown("PRODUCT_DEFINITION_SHAPE", ["''", "''", `${usage}`]),
      )
      repo.add(
        new ContextDependentShapeRepresentation(relationship, usageShape),
      )
    }
  }

  return normalizeStepNumericExponents(repo.toPartFile({ name: productName }))
}
